void PrintTable(lua_State *L)
{
    lua_pushnil(L);

    while(lua_next(L, -2) != 0)
    {
        if(lua_isstring(L, -1))
          printf("%s = %s\n", lua_tostring(L, -2), lua_tostring(L, -1));
        else if(lua_isnumber(L, -1))
          printf("%s = %f\n", lua_tostring(L, -2), lua_tonumber(L, -1));
        else if(lua_istable(L, -1))
          PrintTable(L);

        lua_pop(L, 1);
    }
}




bool		Lua::LookupGlobal(lua_State*state, const String&name, int&out)
{
	if (!state)
		return false;
	lua_getglobal(state, name.c_str());
	if (lua_isnil(state,-1))
	{
		lua_pop(state,1);
		return false;
	}
	out = luaL_ref(state, LUA_REGISTRYINDEX);
	return true;
}

int		Lua::DuplicateReference(lua_State *state, int refID)
{
	PushRegisteredGlobal(state,refID);
	return luaL_ref(state, LUA_REGISTRYINDEX);
}

void		Lua::EraseReference(lua_State *state, int refID)
{
	luaL_unref(state,LUA_REGISTRYINDEX,refID);
}

void Lua::Detail::PopStacked(lua_State*st)
{
	lua_pop(st,1);
}




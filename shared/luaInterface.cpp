	bool Reference::ResetFromStack(const PProgram&st, int at)
	{
		if (!st)
			return false;
		lua_State*state = st->GetState();
		if (lua_gettop(state)< abs(at) || lua_isnil(state,at))
			return false;
		lua_pushvalue(state,at);
		int ref = luaL_ref(state, LUA_REGISTRYINDEX);
		try
		{
			SetReference(st,ref,"");
		}
		catch (...)
		{
			luaL_unref(state,LUA_REGISTRYINDEX,ref);
			throw;
		}
		return true;
	}

	bool Reference::IsTable() const
	{
		if (!Push())
			return false;
		bool rs = lua_istable(GetState(),-1);
		lua_pop(GetState(),1);
		return rs;
	}

	bool Reference::IsFunction() const
	{
		if (!Push())
			return false;
		bool rs = lua_isfunction(GetState(),-1);
		lua_pop(GetState(),1);
		return rs;
	}


	void	Reference::SetGlobal(const String&name)
	{
		if (IsEmpty())
			throw Exception(CLOCATION, "Unable to set global identifier '"+name+"': Reference is empty");
		GetProgram()->SetGlobal(name,*this);
	}


